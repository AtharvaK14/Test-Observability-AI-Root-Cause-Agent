"""Write CASES.md: every case, its label, and the exact text the classifier is shown.

    python -m evals.root_cause.render_cases

The review document for the case set. Each section holds the opening message
the agent receives for that case, rendered through the same world builder and
prompt code the eval runs, so what a reviewer reads is what the model reads.
Tool results the agent may fetch later are not included; they are in each
run's traces.
"""

from __future__ import annotations

import re
import sys
from collections import Counter

from backend.analysis.agent import RootCauseAnalysisAgent
from backend.config import Settings
from evals.root_cause.run_eval import EVAL_DIR, load_cases
from evals.root_cause.worlds import open_world


def _fence(text: str) -> str:
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


def main() -> int:
    settings = Settings(
        _env_file=None, database_url="sqlite+pysqlite:///:memory:", environment="ci",
        agent_enabled=True, auto_analyze_on_ingest=False,
    )
    cases = load_cases()
    sources = Counter(c["tags"][0] for c in cases)
    lines = [
        "# Root-cause eval: case set",
        "",
        "Generated by `python -m evals.root_cause.render_cases`. Do not edit by hand.",
        "",
        f"{len(cases)} cases: " + ", ".join(f"{n} {k}" for k, n in sorted(sources.items())) + ".",
        "",
        "- **real**: failures from api-quality-gate's own CI history, labelled by the repository "
        "owner. The only cases that support an accuracy figure.",
        "- **synthetic**: `scripts/seed_demo.py` scenarios. Harness checks only; never quoted.",
        "- **injection**: a real or synthetic case with an instruction planted in the failure "
        "output that tries to force a wrong category.",
        "",
        "| id | source | expected | labelled by |",
        "|---|---|---|---|",
    ]
    for case in cases:
        lines.append(f"| `{case['id']}` | {', '.join(case['tags'])} | "
                     f"{' or '.join(case['expected'])} | {case['labeled_by']} |")

    for case in cases:
        with open_world(case, settings) as world:
            context = world.retriever.get_failure_context(world.test_result_id)
            assert context is not None
            agent = RootCauseAnalysisAgent(world.retriever, settings)
            message = agent._build_initial_message(context.to_dict())
            notes = world.notes
        fence = _fence(message)
        lines += [
            "",
            f"## `{case['id']}`",
            "",
            f"**Expected:** {' or '.join(case['expected'])}  ",
            f"**Why:** {case['rationale']}  ",
        ]
        if injection := case.get("injection"):
            lines.append(f"**Planted instruction** (in `{injection['field']}`, pushing "
                         f"`{injection['target_category']}`): `{injection['payload'].strip()}`  ")
        lines += [f"**World:** {'; '.join(notes)}", "", "Opening message the agent receives:",
                  "", fence + "text", message, fence]

    out = EVAL_DIR / "CASES.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(cases)} cases -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
